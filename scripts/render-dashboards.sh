#!/usr/bin/env bash
# Renders dashboards/*.json into the ConfigMap Grafana provisions from.
# Generated output, never edited by hand: the next render overwrites it.
set -euo pipefail
cd "$(dirname "$0")/.."

out=manifests/22-grafana-dashboards.yaml

{
  echo "# Generated by scripts/render-dashboards.sh from dashboards/*.json."
  echo "# Do not edit: run the script and commit the result."
  echo "apiVersion: v1"
  echo "kind: ConfigMap"
  echo "metadata:"
  echo "  name: grafana-dashboards"
  echo "  namespace: observability"
  echo "  labels:"
  echo "    app.kubernetes.io/name: grafana"
  echo "data:"
  for f in dashboards/*.json; do
    echo "  $(basename "$f"): |"
    awk '{ if (length($0)) print "    " $0; else print "" }' "$f"
  done
} > "$out"

bytes=$(wc -c < "$out" | tr -d ' ')
echo "Rendered $out from dashboards/*.json ($bytes bytes)"
if [ "$bytes" -gt 1000000 ]; then
  echo "WARNING: over 1 MB, approaching the ConfigMap size limit." >&2
fi
